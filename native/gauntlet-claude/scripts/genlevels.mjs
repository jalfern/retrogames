// Writes Sources/GauntletCore/LevelData.swift from src/games/Gauntlet/levels.js
// (+ the camera constants in minimap.js, and art.js's pixel SPRITE_DATA + MATERIALS): the ten halls as the web computes
// them (stroked walls, punched doors, exits, warps), heroes and monsters, as
// one base64 JSON literal. levels.js stays the only place a hall is drawn;
// check.sh fails on drift (--check).
import { writeFileSync, readFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { LEVELS, HEROES, MONSTERS, HERO_ORDER, W, H } from '../../../src/games/Gauntlet/levels.js'
import { VW, VH, PX } from '../../../src/games/Gauntlet/minimap.js'
import { SPRITE_DATA, MATERIALS } from '../../../src/games/Gauntlet/art.js'

const here = dirname(fileURLToPath(import.meta.url))
const out = join(here, '..', 'Sources', 'GauntletCore', 'LevelData.swift')
const levels = LEVELS.map((l) => ({
    idx: l.idx, name: l.name, material: l.material, grid: l.grid, start: l.start, exit: l.exit,
    doors: l.doors.map((d) => ({ x: d.x, y: d.y, lock: d.lock || null })), props: l.props, gen: l.gen,
    deathAt: l.deathAt, trap: l.trap || null, tele: l.tele || [], warps: l.warps || [],
}))
const json = JSON.stringify({ W, H, VW, VH, PX, LEVELS: levels, HEROES, HERO_ORDER, MONSTERS, SPRITES: SPRITE_DATA, MATERIALS })
const src = `// GENERATED by scripts/genlevels.mjs from src/games/Gauntlet/levels.js — do not edit.\n` +
    `let levelJSONBase64 = "${Buffer.from(json).toString('base64')}"\n`
if (process.argv.includes('--check')) {
    const cur = existsSync(out) ? readFileSync(out, 'utf8') : ''
    if (cur !== src) { console.error('LevelData.swift is stale: run node scripts/genlevels.mjs'); process.exit(1) }
    console.log('levels: LevelData.swift matches levels.js')
} else {
    writeFileSync(out, src)
    console.log(`wrote ${out} (${levels.length} halls)`)
}
