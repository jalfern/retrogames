// Writes Sources/EmberwoodCore/WorldData.swift from src/games/Emberwood/world.js:
// the screens, the shops and the tile constants, as one base64 JSON literal the Swift
// side decodes at startup. world.js stays the only place the vale is drawn;
// rerun this (check.sh does, and fails on drift) after any world edit.
import { writeFileSync, readFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { SCREENS, SHOP, SECRET_SHOP, TS, SW, SH } from '../../../src/games/Emberwood/world.js'
import { proveGame } from '../../../src/games/Emberwood/solver.js'

const here = dirname(fileURLToPath(import.meta.url))
const out = join(here, '..', 'Sources', 'EmberwoodCore', 'WorldData.swift')
// bot.js's static inputs, computed here so JS key order survives: the screen
// graph (Object.entries(SCREENS) x exits/warps/doors order) and the proven route
// (proveGame({bombs:true}).route minus act-two screens) the attract bot plays.
const GRAPH = {}
for (const [id, s] of Object.entries(SCREENS)) {
    GRAPH[id] = []
    for (const dir of Object.keys(s.exits || {})) GRAPH[id].push({ to: s.exits[dir].to, via: 'edge', dir })
    for (const w of s.warps || []) GRAPH[id].push({ to: w.to, via: 'warp', tile: [w.x, w.y] })
    for (const d of s.doors || []) if (d.to) GRAPH[id].push({ to: d.to, via: 'door', tile: [d.x, d.y], did: d.id, kind: d.kind })
}
const PLAN = proveGame({ bombs: true }).route.filter(a => !SCREENS[a.screen] || !SCREENS[a.screen].req).map(a => ({ type: a.type, id: a.id, screen: a.screen }))
const json = JSON.stringify({ TS, SW, SH, SCREENS, SHOP, SECRET_SHOP, BOT: { GRAPH, PLAN } })
const src = `// GENERATED by scripts/genworld.mjs from src/games/Emberwood/world.js — do not edit.\n` +
    `// world.js as base64 JSON (rows are full of # and ", so no Swift literal form is safe)\n` +
    `let worldJSONBase64 = "${Buffer.from(json).toString('base64')}"\n`
const check = process.argv.includes('--check')
if (check) {
    const cur = existsSync(out) ? readFileSync(out, 'utf8') : ''
    if (cur !== src) { console.error('WorldData.swift is stale: run node scripts/genworld.mjs'); process.exit(1) }
    console.log('world: WorldData.swift matches world.js')
} else {
    writeFileSync(out, src)
    console.log(`wrote ${out} (${Object.keys(SCREENS).length} screens)`)
}
